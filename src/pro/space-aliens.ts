/** 避ける語に当たるか(3字以上の語は名前のどこかに含まれたら、2字の語は区切った1つの部分と同じなら当たり)。 */
export const looksReal=(name:string)=>{const bare=name.replace(/[=・]/g,''),pieces=name.split(/[=・]/);return AVOID_WORDS.some(w=>Array.from(w).length>=3?bare.includes(w):pieces.includes(w));};


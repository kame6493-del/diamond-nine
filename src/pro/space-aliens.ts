// 種つきの乱数(xorshift32)。種は文字列から作る。
function hashOf(text:string){let h=2166136261;for(const ch of text){h^=ch.codePointAt(0)!;h=Math.imul(h,16777619)>>>0;}return h||1;}
function seeded(text:string){let x=hashOf(text);return ()=>{x^=x<<13;x>>>=0;x^=x>>>17;x^=x<<5;x>>>=0;return x/4294967296;};}
const pick=<T,>(r:()=>number,list:readonly T[])=>list[Math.floor(r()*list.length)];

// 1つの部分 = 頭の音 + (中の音 0〜1) + 終わりの音。3〜5字。同じ字が3つ続くものは作り直す。
function part(r:()=>number):string{
 for(;;){
  let s=pick(r,heads);
  if(r()<.5)s+=pick(r,mids);
  s+=pick(r,tails);
  const n=Array.from(s).length;
  if(n>=3&&n<=5&&!/(.)/u.test(s))return s;
 }
}
const nameLength=(name:string)=>Array.from(name).length;
/** 種から宇宙人の名前を1つ作る(例: ゾルグ=ヴァックス、キュリリ・ヌーン)。長さは区切りを入れて9字まで。 */
export function alienNameFrom(seed:string):string{
 const r=seeded(seed);
 for(let tries=0;tries<50;tries++){
  const sep=r()<.5?'=':'・';
  const third=r()<.08;
  const name=third?`${part(r)}${sep}${pick(r,['オ','ア','ヴ','ズ'])}${sep}${part(r)}`:`${part(r)}${sep}${part(r)}`;
  if(nameLength(name)<=9&&nameLength(name)>=7&&!looksReal(name))return name;
 }
 return 'ゾルグ=ヴァックス';
}

/** 選手 id → 宇宙人の名前。各球団の名簿(id の順)に、球団ごとの種で名前を割り当てる。重なりは種を進めて作り直す。 */
export function buildAlienNames(roster:readonly {id:string;team:string}[]):Map<string,string>{
 const byTeam=new Map<string,string[]>();
 for(const p of roster){const list=byTeam.get(p.team)??[];list.push(p.id);byTeam.set(p.team,list);}
 const used=new Set<string>(),out=new Map<string,string>();
 for(const team of [...byTeam.keys()].sort()){
  const ids=byTeam.get(team)!.sort();
  ids.forEach((id,slot)=>{
   let n=0,name=alienNameFrom(`space|${team}|${slot}|${n}`);
   while(used.has(name)){n++;name=alienNameFrom(`space|${team}|${slot}|${n}`);}
   used.add(name);out.set(id,name);
  });
 }
 return out;
}

